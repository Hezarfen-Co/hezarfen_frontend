export type Dict = Record<MessageKey, string>;


// Each dictionary is its own chunk: both together were ~290 KB of the initial
// bundle, and a session only ever shows one language at a time. The boot
// (src/index.tsx) awaits the stored locale before the first render, and a
// locale switch awaits the other one before flipping, so `messageFor` never
// has to answer for a language that is not loaded yet.
const loaded: Partial<Record<Locale, Dict>> = {};
const pending: Partial<Record<Locale, Promise<Dict>>> = {};
const loaders: Record<Locale, () => Promise<Dict>> = {
  en: () => import("./locales/en").then((module) => module.en),
  tr: () => import("./locales/tr").then((module) => module.tr),
};

export function loadLocale(locale: Locale): Promise<Dict> {
  const ready = loaded[locale];
  if (ready) return Promise.resolve(ready);
  pending[locale] ??= loaders[locale]().then((dict) => {
    loaded[locale] = dict;
    return dict;
  });
  return pending[locale];
}

/** Install a dictionary synchronously — test setup, where there is no boot to await. */
export function registerLocale(locale: Locale, dict: Dict): void {
  loaded[locale] = dict;
}

export function isLocaleLoaded(locale: Locale): boolean {
  return loaded[locale] !== undefined;
}

/** The text for `key` in `locale`, falling back to whichever other dictionary is loaded. */
export function messageFor(locale: Locale, key: MessageKey): string | undefined {
  return loaded[locale]?.[key] ?? loaded.en?.[key] ?? loaded.tr?.[key];
}

export function formatMessage(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}
